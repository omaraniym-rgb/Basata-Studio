"""Glyph name -> codepoints, presentation form for proofing."""
BASE = {
    'alef': 0x627, 'beh': 0x628, 'teh': 0x62A, 'theh': 0x62B, 'jeem': 0x62C, 'hah': 0x62D, 'khah': 0x62E,
    'dal': 0x62F, 'thal': 0x630, 'reh': 0x631, 'zain': 0x632, 'seen': 0x633, 'sheen': 0x634, 'sad': 0x635,
    'dad': 0x636, 'tah': 0x637, 'zah': 0x638, 'ain': 0x639, 'ghain': 0x63A, 'feh': 0x641, 'qaf': 0x642,
    'kaf': 0x643, 'lam': 0x644, 'meem': 0x645, 'noon': 0x646, 'heh': 0x647, 'waw': 0x648, 'alefMaksura': 0x649,
    'yeh': 0x64A, 'tehMarbuta': 0x629, 'hamza': 0x621, 'alefMadda': 0x622, 'alefHamzaAbove': 0x623,
    'wawHamza': 0x624, 'alefHamzaBelow': 0x625, 'yehHamza': 0x626,
    'fatha': 0x64E, 'damma': 0x64F, 'kasra': 0x650, 'fathatan': 0x64B, 'dammatan': 0x64C, 'kasratan': 0x64D, 'sukun': 0x652,
}
for i in range(10):
    BASE['digit%d' % i] = 0x660 + i
PRES = {  # first presentation form (isol); fina +1, init +2, medi +3
    0x621: 0xFE80, 0x622: 0xFE81, 0x623: 0xFE83, 0x624: 0xFE85, 0x625: 0xFE87, 0x626: 0xFE89, 0x627: 0xFE8D,
    0x628: 0xFE8F, 0x629: 0xFE93, 0x62A: 0xFE95, 0x62B: 0xFE99, 0x62C: 0xFE9D, 0x62D: 0xFEA1, 0x62E: 0xFEA5,
    0x62F: 0xFEA9, 0x630: 0xFEAB, 0x631: 0xFEAD, 0x632: 0xFEAF, 0x633: 0xFEB1, 0x634: 0xFEB5, 0x635: 0xFEB9,
    0x636: 0xFEBD, 0x637: 0xFEC1, 0x638: 0xFEC5, 0x639: 0xFEC9, 0x63A: 0xFECD, 0x641: 0xFED1, 0x642: 0xFED5,
    0x643: 0xFED9, 0x644: 0xFEDD, 0x645: 0xFEE1, 0x646: 0xFEE5, 0x647: 0xFEE9, 0x648: 0xFEED, 0x649: 0xFEEF,
    0x64A: 0xFEF1,
}
OFF = {'': 0, 'fina': 1, 'init': 2, 'medi': 3}


def proof_char(name):
    if name.startswith('lamalef'):
        return chr(0xFEFC if name.endswith('fina') else 0xFEFB)
    base, _, form = name.partition('.')
    cp = BASE[base]
    if cp in PRES:
        return chr(PRES[cp] + OFF[form])
    return ('ـ' if cp >= 0x64B and cp <= 0x652 else '') + chr(cp)
